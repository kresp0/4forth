#!/usr/bin/env python3
# Writes tests/gen/t_examples.txt: every example of help.txt run at the command line, checking that no
# error message appears. Examples that wait for a key, leave the command line or need the text are
# skipped (they are covered by the other tests).
# Copyright (C) 2026 Santiago Crespo
# SPDX-License-Identifier: 0BSD
import os

SKIP = {"KEY", "KEY?", "ACCEPT", "NEW", "BYE", "EDIT", "LINE", "LOCATE", "LOAD", "RUN", "Key codes",
        "WORDS", "DUMP", "Programs", "Start here"}
ERRORS = ["Stack empty", "Stack full", "Return stack", "Compile only", "Dictionary full", "Division error",
          "Name missing", "Unbalanced", "Word in ROM", "Nothing to run", "Unfinished", "Not found"]
os.makedirs("tests/gen", exist_ok=True)
o = ["# Generated by gen_examples.py. Do not edit.", "wait 1.5", "cmd : SQUARE DUP * ;", "wait 0.2"]
title, n = None, 0
for line in open("help.txt", encoding="utf-8"):
    line = line.rstrip("\n")
    if line.startswith("@"):
        title = line[1:]
    elif line.startswith("=") and title not in SKIP:
        ex = line[1:]
        o += ["cmd EMPTY : SQUARE DUP * ;", "wait 0.2", "cmd " + ex, "wait 0.5", "dump " + title]
        o += ["expectnot " + e for e in ERRORS]
        o.append("expectnotre ^%S+ %?%s*$")
        n += 1
o.append("quit")
open("tests/gen/t_examples.txt", "w").write("\n".join(o) + "\n")
print("%d examples" % n)
